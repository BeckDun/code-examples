package Scrabble;

/**
 * Represents the possible directions for word placement on the Scrabble board.
 * Words can be placed either horizontally (left to right) or vertically
 * (top to bottom).
 * @author BeckDun
 */
public enum Direction {
    /**
     * Represents horizontal word placement (left to right)
     */
    HORIZONTAL,

    /**
     * Represents vertical word placement (top to bottom)
     */
    VERTICAL;
}